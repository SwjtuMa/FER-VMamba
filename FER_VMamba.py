class FER_VSSBlock(nn.Module):
    def __init__(
        self,
        hidden_dim: int = 0,
        drop_path: float = 0,
        norm_layer: nn.Module = nn.LayerNorm,
        channel_first=False,
        # =============================
        ssm_d_state: int = 16,
        ssm_ratio=2.0,
        ssm_dt_rank: Any = "auto",
        ssm_act_layer=nn.SiLU,
        ssm_conv: int = 3,
        ssm_conv_bias=True,
        ssm_drop_rate: float = 0,
        ssm_init="v0",
        forward_type="v2",
        # =============================
        mlp_ratio=4.0,
        mlp_act_layer=nn.GELU,
        mlp_drop_rate: float = 0.0,
        gmlp=False,
        # =============================
        use_checkpoint: bool = False,
        post_norm: bool = False,
        **kwargs,
    ):
        super().__init__()
        self.ssm_branch = ssm_ratio > 0
        self.mlp_branch = mlp_ratio > 0
        self.use_checkpoint = use_checkpoint
        self.post_norm = post_norm
        if self.ssm_branch:
            self.norm = norm_layer(hidden_dim//2)
            self.op = SS2D(
                d_model=hidden_dim//2, 
                d_state=ssm_d_state, 
                ssm_ratio=ssm_ratio,
                dt_rank=ssm_dt_rank,
                act_layer=ssm_act_layer,
                # ==========================
                d_conv=ssm_conv,
                conv_bias=ssm_conv_bias,
                # ==========================
                dropout=ssm_drop_rate,
                # bias=False,
                # ==========================
                # dt_min=0.001,
                # dt_max=0.1,
                # dt_init="random",
                # dt_scale="random",
                # dt_init_floor=1e-4,
                initialize=ssm_init,
                # ==========================
                forward_type=forward_type,
                channel_first=channel_first,
            )       
        self.drop_path = DropPath(drop_path)
        if self.mlp_branch:
            _MLP = Mlp if not gmlp else gMlp
            self.norm2 = norm_layer(hidden_dim//2)
            mlp_hidden_dim = int(hidden_dim//2 * mlp_ratio)
            self.mlp = _MLP(in_features=hidden_dim//2, hidden_features=mlp_hidden_dim//2, act_layer=mlp_act_layer, drop=mlp_drop_rate, channels_first=channel_first)
        self.conv33conv33conv11 = nn.Sequential(
        nn.Conv2d(in_channels=hidden_dim//2,out_channels=hidden_dim//2, kernel_size=1, bias=False),  
        nn.BatchNorm2d(hidden_dim//2),
        nn.ReLU(inplace=True)  ,
        ChannelSpatialAttentionBlock(hidden_dim//2) , 
        nn.Conv2d(hidden_dim//2, hidden_dim//2, kernel_size=1, bias=False)  ,
        nn.BatchNorm2d(hidden_dim//2) 
        )
        self.finalconv11 = nn.Conv2d(in_channels=hidden_dim, out_channels=hidden_dim, kernel_size=1, stride=1)
    def forward(self, input: torch.Tensor): 
        input_left, input_right = input.chunk(2,dim=-1)  
        if self.ssm_branch:
            x = input_right + self.drop_path(self.op(self.norm(input_right))) 
        if self.mlp_branch:
            x = x + self.drop_path(self.mlp(self.norm2(x))) 
        input_left = input_left.permute(0,3,1,2).contiguous()     
        input_left = self.conv33conv33conv11(input_left)
        x = x.permute(0,3,1,2).contiguous()   
        output = torch.cat((input_left,x),dim=1)  
        output = self.finalconv11(output).permute(0,2,3,1).contiguous()
        return output 
    
class ChannelSpatialAttentionBlock(nn.Module):  
    def __init__(self, in_channels, reduction=16):  
        super(ChannelSpatialAttentionBlock, self).__init__()   
        self.se_block = nn.Sequential(  
            nn.AdaptiveAvgPool2d(1),  
            nn.Conv2d(in_channels, in_channels // reduction, 1, bias=False),  
            nn.ReLU(inplace=True),  
            nn.Conv2d(in_channels // reduction, in_channels, 1, bias=False),  
            nn.Sigmoid()  
        )   
        self.conv1x1 = nn.Conv2d(2, 1, 1, bias=False)  
        self.sigmoid = nn.Sigmoid()  
    def forward(self, x):  
        se_attention = self.se_block(x)  
        avg_out = torch.mean(x, dim=1, keepdim=True)  
        max_out, _ = torch.max(x, dim=1, keepdim=True)  
        spatial_feature = torch.cat([avg_out, max_out], dim=1)  
        spatial_attention = self.sigmoid(self.conv1x1(spatial_feature))   
        output = se_attention * x * spatial_attention  
        return output   
class MixedFeatureNet(Module):
    def __init__(self, embedding_size=256, out_h=7, out_w=7):
        super(MixedFeatureNet, self).__init__()   
        self.conv1 = Conv_block(3, 64, kernel=(3, 3), stride=(2, 2), padding=(1, 1))
